/**
 * Provider-neutral file storage seam (issue #16).
 *
 * This module is the boundary between SARbase domain code and any object
 * storage backend (local filesystem, S3-compatible object store). Domain
 * records persist only `storageProvider` + `storageKey`; provider SDK
 * objects, URLs, and raw error text never cross this boundary.
 *
 * PRODUCT BOUNDARY: this is documentary storage infrastructure only.
 * Files are untrusted content — SARbase stores, serves, and audits them
 * as records; nothing here inspects file contents or infers operational
 * conclusions from them.
 *
 * Storage keys are opaque identifiers generated by the domain layer
 * (e.g. `organizations/<orgId>/attachments/<uuid>`). Providers must never
 * derive addressing from filenames, member names, or record titles.
 *
 * Adding a provider later: implement `FileStorageProvider`, register it
 * in `resolve.ts` and extend `StorageEnvironment` in `src/lib/env.ts` —
 * the domain layer (`src/lib/domain/attachments.ts`) does not change.
 */

/** Normalized provider failure classification. */
export type StorageErrorCode =
  | "config_missing"
  | "object_not_found"
  | "precondition_failed"
  | "provider_unavailable"
  | "provider_error";

/**
 * Storage failure with a provider-independent `code` and a safe,
 * operator-facing `message`. Raw provider error text (which may echo
 * credentials, endpoints, request IDs, or bucket paths) is retained in
 * `cause` for server-side diagnostics and must never be rendered or
 * returned to clients.
 */
export class StorageError extends Error {
  readonly code: StorageErrorCode;
  override readonly cause: unknown;

  constructor(code: StorageErrorCode, message: string, cause?: unknown) {
    super(message);
    this.name = "StorageError";
    this.code = code;
    this.cause = cause;
  }
}

/** Thrown when provider configuration is missing or inconsistent. */
export class StorageConfigError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "StorageConfigError";
  }
}

/** Streamed object body returned by `openRead`. */
export interface StorageObjectStream {
  /** Web ReadableStream of the object's bytes — never the whole body. */
  stream: ReadableStream<Uint8Array>;
  sizeBytes: number;
}

export interface StorageObjectStat {
  sizeBytes: number;
  contentType: string | null;
  /**
   * Opaque version token for the observed object (S3 ETag, memory
   * content hash). Direct-upload finalization pins the promotion copy
   * to the verified object via `ifMatchEtag` — the presigned POST stays
   * valid until expiry, so without a precondition the staged object
   * could be re-uploaded between verification and promote.
   */
  etag?: string | null;
  /**
   * Provider's object-version identifier when the store versions
   * objects (S3 `VersionId` on a versioned bucket). `null`/`undefined`
   * on unversioned stores. Recorded on the Attachment so a scan result
   * can be bound to the exact bytes it evaluated.
   */
  versionId?: string | null;
}

/**
 * Identity of the object version a write produced — returned by `put`
 * and `promoteObject` so the domain can bind scan results to the exact
 * stored bytes. `null` values mean the store does not version or did
 * not report it.
 */
export interface StoredObjectVersion {
  versionId: string | null;
  etag: string | null;
}

/**
 * A short-lived, narrowly scoped target the browser uploads one object
 * to DIRECTLY (e.g. an S3 presigned POST). The server never sees the
 * bytes — uploads beyond the hosting platform's request-body limit stay
 * possible. `fields` are the signed grant itself: the client MUST send
 * them verbatim in the multipart form (they bind the exact key, the
 * declared Content-Type, and the byte-size range at the store edge).
 * The URL is a write-only capability — never logged or persisted.
 */
export interface DirectUploadTarget {
  url: string;
  method: "POST";
  fields: Record<string, string>;
  expiresAt: Date;
}

export interface FileStorageProvider {
  /**
   * Stable identifier persisted on `Attachment.storageProvider`
   * ("local", "s3"). Never a URL or provider-specific term.
   */
  readonly providerName: string;

  /**
   * Store `body` under `key`. Callers must provide the complete byte
   * sequence (uploads are size-capped well below memory pressure). The
   * provider owns durability semantics; a resolved promise means the
   * object is stored.
   */
  /**
   * Returns the stored object's version identity (versioned stores) —
   * `null` fields when the store cannot provide one.
   */
  put(
    key: string,
    body: Uint8Array,
    contentType: string,
  ): Promise<StoredObjectVersion>;

  /**
   * Open the object for streaming reads. Throws StorageError
   * `object_not_found` when the key does not exist.
   */
  openRead(key: string): Promise<StorageObjectStream>;

  /**
   * Object metadata without bytes. Returns null when the object does
   * not exist.
   */
  head(key: string): Promise<StorageObjectStat | null>;

  /**
   * Delete the object. Deleting a non-existent key is a no-op success —
   * idempotent deletion keeps repeated delete actions honest.
   */
  delete(key: string): Promise<void>;

  /**
   * OPTIONAL capability — issue a direct-upload target for `key`
   * (providers without one simply omit this and callers fall back to
   * the server-proxied path). The target MUST be scoped to exactly this
   * key, write-only, and expire quickly. `contentType` and `sizeBytes`
   * are bound into the grant where the provider supports it.
   */
  createUploadTarget?(
    key: string,
    options: {
      contentType: string;
      sizeBytes: number;
      expiresInSeconds: number;
    },
  ): Promise<DirectUploadTarget>;

  /**
   * OPTIONAL capability — move `stagingKey` to `finalKey` server-side
   * (an object-store copy, never a byte round-trip through the app),
   * then remove the staging object. Present iff `createUploadTarget` is:
   * a staged direct upload must be promotable before it is recorded.
   * `options.ifMatchEtag` makes the copy conditional on the source
   * object still being the verified version — the grant that wrote it
   * is live until expiry and could overwrite it mid-finalize. Providers
   * that cannot enforce the precondition ignore it (in-memory fakes
   * model it for tests).
   */
  promoteObject?(
    stagingKey: string,
    finalKey: string,
    options?: { ifMatchEtag?: string },
  ): Promise<StoredObjectVersion>;

  /**
   * OPTIONAL capability — read a single object tag (S3
   * `GetObjectTagging`, e.g. `GuardDutyMalwareScanStatus`). Used only by
   * scan reconciliation; `null` when the tag is absent or the provider
   * does not support tags. `versionId` pins the read to a specific
   * object version where the store supports it — the current object's
   * tags describe bytes that may differ from the recorded version.
   */
  getObjectTag?(
    key: string,
    tagKey: string,
    versionId?: string | null,
  ): Promise<string | null>;
}
